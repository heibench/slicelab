"""Two hashes of one artifact, and the refusal to pretend they are the same thing.

`raw_sha256` identifies the file: every byte, including the line that changes on
every run. It answers "is this the file that lock describes" and nothing else.

`normalized_sha256` answers the harder question -- "would slicing this again produce
the same toolpaths" -- and it only means that if the variation has actually been
removed. Measured on 2026-10-05, PrusaSlicer 2.9.6, the same cube sliced twice on one
host: 23422 lines and 604407 bytes each, **one** line different, line 0's
`; generated by PrusaSlicer 2.9.6 on <date> at <time> UTC`. The byte size is
identical because the timestamp's width is fixed, so a size comparison would have
called the two files the same.

D9's rule is what makes the second hash worth having: a substitution count of 0 on a
format slicelab claimed to normalize means the header was not recognised, so the hash
is withheld, an `unknowns` code is recorded, and the outcome is `incomplete` -- never
a silent fallback to hashing raw bytes under the normalized name. Since `slice`
promotes only on an outcome it stands behind, that also means nothing is handed over:
an artifact slicelab cannot read the header of is one it does not understand, and the
engine changing its header is exactly when slicelab should stop rather than ship a
lock claiming less than a reader will assume.

A binary container is a different case and is not a failure. D10 settles it: `GCDE`
carries no text footer at all, so normalization is never attempted, the hash is null
with its own code, and the run stays `sliced`.
"""

from __future__ import annotations

import hashlib
from dataclasses import dataclass
from pathlib import Path
from typing import Final

__all__ = ["Normalized", "raw_sha256"]

#: Why a normalized hash is withheld after normalization was attempted and changed
#: nothing. The format is not the one slicelab knows how to compare.
HEADER_NOT_RECOGNISED: Final = "artifact_header_not_recognised"

#: Why normalization was never attempted (D10).
CONTAINER_IS_BINARY: Final = "container_carries_no_text_footer"

#: Why normalization was never attempted when the container itself is unknown.
#:
#: Distinct from the one above, because that one is established -- `GCDE` has no text
#: footer and slicelab measured that. This one says slicelab could not tell what the
#: container is, which is a different claim and the one `Container.UNDETERMINED`'s own
#: docstring makes. Reporting it as "carries no text footer" would assert as measured
#: exactly what was not.
CONTAINER_UNDETERMINED: Final = "container_not_identified"


def raw_sha256(artifact: Path) -> str:
    """sha256 of every byte of one file (D9)."""
    with artifact.open("rb") as handle:
        return hashlib.file_digest(handle, "sha256").hexdigest()


@dataclass(frozen=True)
class Normalized:
    """The artifact's hash with its run-to-run variation removed, or why there is none.

    `substitutions` travels with the hash rather than beside it because the count is
    what makes the hash interpretable: 1 says the header was found and replaced, and
    0 says the pattern matched nothing, which is not a normalized hash of anything.
    """

    substitutions: int
    sha256: str | None = None
    reason: str | None = None

    def __post_init__(self) -> None:
        if (self.sha256 is None) == (self.reason is None):
            raise ValueError("a normalized hash is a digest or a reason there is none, never both")
        if self.sha256 is not None and self.substitutions < 1:
            raise ValueError(
                f"{self.substitutions} substitutions cannot produce a normalized hash: "
                "nothing was normalized, so this would be the raw hash under another name"
            )

    def as_table(self) -> dict[str, object]:
        table: dict[str, object] = {"substitutions": self.substitutions}
        if self.sha256 is not None:
            table["sha256"] = self.sha256
        if self.reason is not None:
            table["reason"] = self.reason
        return table


def normalized_sha256(text: str, substitute: object) -> Normalized:
    """Hash `text` with its volatile header replaced, through the engine's own rule.

    `substitute` is the adapter's `(text) -> (text, count)`. The count decides: a
    zero means the engine's format is not the one that rule was measured against, and
    D9 withholds the hash rather than quietly hashing the bytes as they came.
    """
    rewritten, count = substitute(text)  # type: ignore[operator]
    if count < 1:
        return Normalized(substitutions=0, reason=HEADER_NOT_RECOGNISED)
    return Normalized(
        substitutions=count,
        sha256=hashlib.sha256(rewritten.encode("utf-8", errors="surrogateescape")).hexdigest(),
    )

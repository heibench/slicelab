"""A reported number cannot exist without its source, and a zero is not a mass.

`Stat` is a class rather than a float because of two states the lock has to be able
to tell apart and TOML cannot express: a number that was measured, and a number the
engine printed that is not a measurement. TOML has no null, so the second is a table
with no `value` and a `reason`, and the invariant here is what stops a third state
-- a bare number with nothing saying where it came from -- existing at all.
"""

from __future__ import annotations

import pytest

from slicelab.adapters.prusaslicer import _duration_seconds, _read_artifact_stats
from slicelab.stats import DENSITY_ZERO, PER_FILAMENT_LIST, Stat, StatError
from slicelab.vocab import (
    FILAMENT_CM3,
    FILAMENT_G,
    FILAMENT_MM,
    GCODE_FOOTER,
    LAYERS,
    PRINT_TIME_S,
    REPORTED_STATS,
    SLICER_MARKER_COUNT,
)

#: A footer in the engine's own shape, written here rather than copied from an
#: artifact: slicelab ships zero engine-derived bytes (D11), and what is under test
#: is the parse, which needs the shape and not the content. The numbers are the ones
#: measured on 2026-10-05 so a reader can line this up against that run.
STOCK_FOOTER = """\
; generated by a slicer
G1 X0 Y0
;LAYER_CHANGE
;LAYER_CHANGE
; filament used [mm] = 1251.87
; filament used [cm3] = 3.01
; filament used [g] = 3.73
; total filament used [g] = 3.73
; estimated printing time (normal mode) = 24m 42s
; filament_density = 1.24
; layer_height = 0.2
"""

#: The same slice with `--filament-density=0`. Measured: the per-filament mass line
#: disappears, the total still prints `0.00`, and the extrusion is unchanged.
WEIGHTLESS_FOOTER = (
    STOCK_FOOTER.replace("; filament used [g] = 3.73\n", "")
    .replace("; total filament used [g] = 3.73", "; total filament used [g] = 0.00")
    .replace("; filament_density = 1.24", "; filament_density = 0")
)


def test_a_stat_without_a_source_is_refused() -> None:
    with pytest.raises(StatError, match="carries its source"):
        Stat(source="", key="; filament used [mm]", value=1.0)
    with pytest.raises(StatError, match="carries its source"):
        Stat(source=GCODE_FOOTER, key="", value=1.0)


def test_a_stat_is_a_value_or_a_reason_and_never_both() -> None:
    """The invariant that makes an unexplained absence unrepresentable.

    Both set would let a reader take the number and ignore the reason; neither set
    is a field that says nothing at all. The lock has no use for either.
    """
    with pytest.raises(StatError, match="never both"):
        Stat(source=GCODE_FOOTER, key="; total filament used [g]", value=0.0, reason=DENSITY_ZERO)
    with pytest.raises(StatError, match="never neither"):
        Stat(source=GCODE_FOOTER, key="; total filament used [g]")


def test_a_measured_stat_writes_its_value_and_an_unmeasurable_one_does_not() -> None:
    measured = Stat(source=GCODE_FOOTER, key="; filament used [mm]", value=1251.87)
    assert measured.measured
    assert measured.as_table() == {
        "source": GCODE_FOOTER,
        "key": "; filament used [mm]",
        "value": 1251.87,
    }

    withheld = Stat(source=GCODE_FOOTER, key="; total filament used [g]", reason=DENSITY_ZERO)
    assert not withheld.measured
    assert "value" not in withheld.as_table(), "a 0 nobody measured would be read as a mass"
    assert withheld.as_table()["reason"] == DENSITY_ZERO


def test_zero_is_a_legitimate_measurement() -> None:
    """The control for the one above. A real 0 must still be recordable, or the
    invariant would be refusing measurements rather than guesses."""
    assert Stat(
        source=GCODE_FOOTER, key="; total filament used for wipe tower [g]", value=0.0
    ).measured


def test_every_field_the_reader_emits_is_in_the_closed_set() -> None:
    """The lock's stat names are closed (`REPORTED_STATS`) so a reader can ask
    whether a name belongs. A reader that invents one defeats that."""
    assert set(_read_artifact_stats(STOCK_FOOTER)) <= REPORTED_STATS


def test_a_stock_footer_reads_as_five_measured_numbers() -> None:
    stats = _read_artifact_stats(STOCK_FOOTER)

    assert stats[FILAMENT_MM].value == 1251.87
    assert stats[FILAMENT_CM3].value == 3.01
    assert stats[FILAMENT_G].value == 3.73
    assert stats[PRINT_TIME_S].value == 1482, "24m 42s"
    assert all(stat.measured for stat in stats.values())


def test_the_layer_count_is_a_counted_marker_and_says_so() -> None:
    """PrusaSlicer states no layer count. Counting is the only source, and the lock
    has to say that rather than let a counted number read as a stated one."""
    layers = _read_artifact_stats(STOCK_FOOTER)[LAYERS]
    assert layers.value == 2
    assert layers.source == SLICER_MARKER_COUNT
    assert layers.key == ";LAYER_CHANGE"


def test_a_zero_density_mass_is_withheld_with_its_reason() -> None:
    """The case the class exists for. The extrusion is real and the mass is not."""
    stats = _read_artifact_stats(WEIGHTLESS_FOOTER)

    assert stats[FILAMENT_MM].value == 1251.87, "the extrusion is unchanged"
    assert stats[FILAMENT_G].value is None
    assert stats[FILAMENT_G].reason == DENSITY_ZERO
    assert "value" not in stats[FILAMENT_G].as_table()


def test_a_density_of_zero_in_any_position_withholds_the_total() -> None:
    """The total is a sum. One weightless filament makes the sum not the print's mass."""
    multi = STOCK_FOOTER.replace("; filament_density = 1.24", "; filament_density = 1.24,0")
    assert _read_artifact_stats(multi)[FILAMENT_G].reason == DENSITY_ZERO


def test_a_mass_with_no_declared_density_is_withheld() -> None:
    """Absent is not 1.0. Without a density the engine's grams cannot be checked."""
    undeclared = STOCK_FOOTER.replace("; filament_density = 1.24\n", "")
    assert _read_artifact_stats(undeclared)[FILAMENT_G].reason == DENSITY_ZERO


def test_a_field_the_engine_never_printed_is_absent_rather_than_excused() -> None:
    """Absent and present-with-a-reason are different claims: the first says this
    engine does not report it, the second says it did and the number is unusable."""
    silent = STOCK_FOOTER.replace("; filament used [cm3] = 3.01\n", "")
    stats = _read_artifact_stats(silent)
    assert FILAMENT_CM3 not in stats
    assert FILAMENT_MM in stats


def test_an_artifact_with_no_markers_reports_no_layer_count() -> None:
    bare = "; filament used [mm] = 1251.87\n; filament_density = 1.24\n"
    assert LAYERS not in _read_artifact_stats(bare)


@pytest.mark.parametrize(
    ("spelling", "seconds"),
    [
        ("24m 42s", 1482),
        ("1h 2m 3s", 3723),
        ("2d 1h", 176400),
        ("45s", 45),
    ],
)
def test_a_duration_the_engine_spells_is_read(spelling: str, seconds: int) -> None:
    assert _duration_seconds(spelling) == seconds


@pytest.mark.parametrize("spelling", ["", "about an hour", "24m 42", "1w 2d", "m42s"])
def test_a_duration_spelled_some_other_way_is_not_half_read(spelling: str) -> None:
    """Half a duration is a wrong number rather than a smaller one, so an unreadable
    unit makes the whole value absent instead of contributing nothing."""
    assert _duration_seconds(spelling) is None


def test_a_per_filament_list_is_withheld_rather_than_dropped() -> None:
    """A multi-material print writes `; filament used [mm] = 1251.87, 300.00`, and this
    engine states no `total filament used [mm]` to go with it -- unlike the mass.

    Dropping the field would read as "this engine reports nothing of the kind", and it
    reported plenty. Summing would be slicelab's arithmetic wearing the engine's key.
    """
    multi = STOCK_FOOTER.replace(
        "; filament used [mm] = 1251.87", "; filament used [mm] = 1251.87, 300.00"
    ).replace("; filament used [cm3] = 3.01", "; filament used [cm3] = 3.01, 0.72")

    stats = _read_artifact_stats(multi)

    for field in (FILAMENT_MM, FILAMENT_CM3):
        assert field in stats, f"{field} was dropped, which claims the engine said nothing"
        assert stats[field].value is None
        assert stats[field].reason == PER_FILAMENT_LIST
    assert stats[FILAMENT_G].value == 3.73, "the mass HAS a stated total, so it survives"


def test_the_layer_count_ignores_the_marker_inside_the_configuration() -> None:
    """The configuration block echoes every setting back, so an author whose
    `layer_gcode` holds the literal would have it counted once more."""
    echoed = STOCK_FOOTER + "; prusaslicer_config = begin\n; layer_gcode = ;LAYER_CHANGE\n"
    assert _read_artifact_stats(echoed)[LAYERS].value == 2, "the footer's copy was counted"

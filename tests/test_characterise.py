"""The option-to-key map, and the three ways a probe can measure silence.

``notes/critique.md`` G2 is the reason the map is probed rather than derived, and
the reason it must not be derived is reproduced here as an engine test: on
PrusaSlicer 2.9.6 ``--after-layer-gcode`` writes ``layer_gcode``, and a
dash-to-underscore readback calls that a perfectly applied key ``absent``.

Most of this file needs no engine. The classification rules are where the probe
can silently become wrong -- an engine that writes no artifact at exit 0 would
otherwise read as an option that moved every key at once -- so each of them is
driven against a stand-in and has a red state on every runner, including the ones
with no slicer installed.
"""


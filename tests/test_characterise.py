def test_the_environment_the_cache_lands_in_is_part_of_the_test(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    """No test here may write into the real user's cache.

    ``XDG_CACHE_HOME`` is exactly the ambient value a defect hides behind, so it
    is parametrized rather than inherited -- and this asserts the parametrization
    is the thing being read.
    """
    monkeypatch.setenv("XDG_CACHE_HOME", str(tmp_path))
    assert tmp_path in cache_path_for(PRUSASLICER, "2.9.6").parents
    monkeypatch.delenv("XDG_CACHE_HOME")
    assert os.environ.get("XDG_CACHE_HOME") is None
    assert Path.home() in cache_path_for(PRUSASLICER, "2.9.6").parents

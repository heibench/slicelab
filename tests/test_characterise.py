    before = dict(entries)
    _confirm_the_inert(entries, PRUSASLICER, FOUND, _PROBE, sidecar, BASELINE, (), timeout=1.0)
    assert entries == before
    assert engine.calls == 0, "the confirmation pass reached an option it must not touch"



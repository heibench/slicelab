def test_a_sentinel_that_resolves_to_the_default_is_not_an_answer(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    """The defect this probe shipped for one measurement, as a regression test.

    D5: PrusaSlicer's boolean options validate nothing, and anything that is not
    literally ``1`` resolves to ``0``. ``--spiral-vase=SLICELABPROBE`` therefore
    exits 0, resolves to the ``0`` already in the dump, and moves no key. Stopping
    at the first accepted sentinel classified 110 real options -- ``--spiral-vase``,
    ``--support-material`` and ``--thin-walls`` among them -- as writing no
    configuration, which is the opposite of the truth and would keep every one of
    them out of the map.
    """
    true_word, false_word = PAIRS[4]
    outcome, entry, _ = _probe(
        tmp_path,
        monkeypatch,
        lambda s: (
            (0, "", _ini({**BASELINE, "beta": true_word}))
            if s == true_word
            else (0, "", _ini({**BASELINE, "beta": false_word}))
        ),
    )
    assert outcome is ProbeOutcome.MAPPED
    assert entry is not None and entry.keys == ("beta",)



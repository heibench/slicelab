# -- the boundary: the driver must stay ignorant of every engine ---------------


def _imported_modules(path: Path) -> set[str]:
    tree = ast.parse(path.read_text(encoding="utf-8"), filename=str(path))
    names: set[str] = set()
    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            names.update(alias.name for alias in node.names)
        elif isinstance(node, ast.ImportFrom) and node.module and node.level == 0:
            names.add(node.module)
    return names


def test_the_probe_driver_imports_no_adapter_module() -> None:
    """It may know that engines exist. It may not know which one it is driving.

    ``slicelab.adapters`` is the facade holding ``EngineSpec`` and ``OptionProbe``;
    reaching past it to ``slicelab.adapters.prusaslicer`` is how ``--help-fff``
    parsing would arrive in the core, one convenience at a time.
    """
    imported = _imported_modules(PACKAGE / "engine" / "characterise.py")
    reached = sorted(m for m in imported if m.startswith("slicelab.adapters."))
    assert reached == [], f"the probe driver reached into an adapter: {reached}"


def test_the_import_boundary_test_is_not_vacuous() -> None:
    """The adapter modules must be reachable, or the check above finds nothing."""
    imported = _imported_modules(PACKAGE / "adapters" / "__init__.py")
    assert any(m.startswith("slicelab.adapters.") for m in imported)


# -- against a real engine -----------------------------------------------------


def _live_vocabulary(spec: EngineSpec, tmp_path: Path) -> tuple[tuple[str, ...], Mapping[str, str]]:
    """This build's own option names and config keys, read from the engine."""
    from slicelab.engine.discover import discover

    probe = spec.option_probe
    assert probe is not None and spec.readback_flag is not None
    found = discover(spec)
    if found.form is None:
        pytest.skip(f"{spec.name}: {found.reason}")
    sidecar = tmp_path / "readback"
    run(argv_for(found.form, (f"{spec.readback_flag}={sidecar}",), (str(sidecar),)), timeout=90.0)
    if not sidecar.exists() or sidecar.stat().st_size == 0:
        pytest.skip(f"{spec.name} wrote no readback for a request with nothing set")
    baseline = probe.read_config(sidecar.read_text(encoding="utf-8", errors="replace"))
    listing = ""
    if probe.enumerate_argv:
        completed = run(argv_for(found.form, probe.enumerate_argv, ()), timeout=90.0)
        listing = completed.stdout + completed.stderr
    return probe.candidates(listing, baseline), baseline


def _scanned_sources() -> list[Path]:
    """Every module outside ``adapters/``. The claim is about all of them."""
    adapters = PACKAGE / "adapters"
    return [p for p in sorted(PACKAGE.rglob("*.py")) if adapters not in p.parents]


def test_no_live_engine_key_or_option_appears_outside_the_adapters(
    any_engine: EngineSpec, tmp_path: Path
) -> None:
    """D26's claim, measured against the vocabulary the engine states today.

    ``tests/test_names_confined.py`` scans the modules directly under
    ``slicelab/``; ``slicelab/engine/`` is not among them, and the probe driver
    lives there. Rather than widen that decision's whitelist -- the dumping ground
    its supersede clause warns about -- the same claim is made the expensive way:
    read this build's own config keys, and require that not one of them survives
    ``undeclared_terms`` anywhere outside ``slicelab/adapters/``.

    Reusing that function rather than scanning words is not incidental. A blanket
    "no engine word anywhere" scan is red on day one, because ``output``,
    ``load``, ``save`` and ``info`` are engine option names and ordinary English
    at the same time -- measured against this corpus, a word scan flags 54 terms
    across eleven clean modules, nearly all of them prose. D26 settled that
    already: a literal is either prose or vocabulary, and prose is not a leak.

    Scoped to the **config-key namespace**, which is D26's own scope rather than a
    convenient narrowing. The option names are the map's keys and the config keys
    are its values, and only the values are what a readback compares against.
    Putting the option names back costs exactly one false positive, worth naming
    because it is the shape of the whole problem: ``engine/identity.py`` runs
    ``flatpak info`` to read a deployment commit, and ``--info`` is also a
    PrusaSlicer option, so the literal ``"info"`` there is a Flatpak subcommand
    colliding with an engine option and not a leak of anything.
    """
    _options, baseline = _live_vocabulary(any_engine, tmp_path)
    vocabulary = set(baseline)
    assert len(vocabulary) > 200, (
        f"{any_engine.name} stated {len(vocabulary)} keys; it was not read"
    )

    offenders: list[str] = []
    for path in _scanned_sources():
        terms = set(undeclared_terms(path.read_text(encoding="utf-8"), str(path)))
        for term in sorted(vocabulary & terms):
            offenders.append(f"{path.relative_to(PACKAGE)} names {term!r}")
    assert offenders == [], (
        "an engine's own vocabulary reached a literal outside slicelab/adapters/: "
        + "; ".join(offenders)
    )


